CREATE TABLE IF NOT EXISTS seed_metadata (
    seed_key TEXT PRIMARY KEY,
    seeded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- schema.sql guarantees Alice/Bob/Charlie at user IDs 1/2/3.
-- Demo tasks are seeded once on fresh initialization; existing databases (even if all tasks were deleted)
-- record completion without resurrecting deleted rows on migration replay.
DO $$
DECLARE
    tasks_existed BOOLEAN := to_regclass('public.tasks') IS NOT NULL;
BEGIN
    CREATE TABLE IF NOT EXISTS tasks (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL CHECK (length(btrim(title)) > 0),
        description TEXT,
        status TEXT NOT NULL CHECK (status IN ('todo', 'in_progress', 'done')),
        priority TEXT NOT NULL CHECK (priority IN ('low', 'medium', 'high')),
        assigned_to INTEGER NOT NULL REFERENCES users(id),
        created_by INTEGER NOT NULL REFERENCES users(id),
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        seed_key TEXT UNIQUE
    );

    IF tasks_existed THEN
        INSERT INTO seed_metadata (seed_key)
        VALUES ('recoverboard:slice2:tasks')
        ON CONFLICT (seed_key) DO NOTHING;
    ELSIF NOT EXISTS (
        SELECT 1 FROM seed_metadata WHERE seed_key = 'recoverboard:slice2:tasks'
    ) THEN
        INSERT INTO tasks (title, description, status, priority, assigned_to, created_by, seed_key) VALUES
        ('Prepare recovery plan','Review priorities and agree on next steps.','todo','high',1,3,'recoverboard:slice2:01'),
        ('Audit dependencies',NULL,'todo','medium',2,1,'recoverboard:slice2:02'),
        ('Update documentation','Document deployment notes.','todo','low',3,2,'recoverboard:slice2:03'),
        ('Review pull requests',NULL,'in_progress','high',2,3,'recoverboard:slice2:04'),
        ('Restore staging environment','Coordinate infrastructure checks.','in_progress','medium',1,2,'recoverboard:slice2:05'),
        ('Check monitoring',NULL,'in_progress','low',3,1,'recoverboard:slice2:06'),
        ('Resolve login issue','Investigate reported behavior.','done','high',3,2,'recoverboard:slice2:07'),
        ('Validate backups',NULL,'done','medium',1,3,'recoverboard:slice2:08'),
        ('Close old incidents','Confirm resolution with the team.','done','low',2,1,'recoverboard:slice2:09'),
        ('Plan team handoff',NULL,'todo','high',3,3,'recoverboard:slice2:10')
        ON CONFLICT (seed_key) DO NOTHING;

        INSERT INTO seed_metadata (seed_key)
        VALUES ('recoverboard:slice2:tasks')
        ON CONFLICT (seed_key) DO NOTHING;
    END IF;
END $$;
